    const lower = String(text || "").toLowerCase();
    const score = {};
    for (const k of PET.EMOTION_KEYS) score[k] = 0;
    for (const [k, words] of Object.entries(KW)) {
      if (score[k] === undefined) continue;   // 情緒被移除時自動忽略
      for (const w of words) {
        const needle = w.toLowerCase();
        let idx = lower.indexOf(needle);
        while (idx !== -1) {
          const before = lower.slice(Math.max(0, idx - 2), idx);
          const flip = NEG.test(before);
          if (flip && POSITIVE.has(k)) score.sad += 1.6;
          else score[k] += needle.length >= 2 ? 2 : 1;
          idx = lower.indexOf(needle, idx + needle.length);
        }
      }
    }
    for (const [set, k] of Object.entries(EMOJI)) {
      if (score[k] === undefined) continue;
      for (const ch of set) if (text.includes(ch)) score[k] += 2.2;
    }

    const bangs = (text.match(/[!！]/g) || []).length;
    if (bangs >= 2) { score.excited += 1.2; score.angry += 0.6; }
    if (bangs >= 4) score.furious += 1.2;
    if (/[?？]/.test(text)) { score.confused += 0.8; score.curious += 0.5; }
    if (/[?？]{2,}/.test(text)) score.confused += 1.2;
    if (/[…⋯]|\.{3}/.test(text)) { score.sad += 0.7; score.bored += 0.4; }

    let best = "calm", bv = 0;
    for (const k of PET.EMOTION_KEYS) if (score[k] > bv) { bv = score[k]; best = k; }
    const intensity = bv >= 5 ? 3 : bv >= 2.5 ? 2 : 1;
    // 必須先完成本地關鍵詞評分、選出 matchedEmotion，再套黑名單。若在 KW
    // 迴圈前就移除 key，「你很煩」會靜默落到其他最高分，測不到防線是否真的生效。
    const matchedEmotion = bv === 0 ? "calm" : best;
    return {
      emotion: PET.sanitizeEmotion(matchedEmotion),
      matchedEmotion,
      intensity,
      score: bv,
    };
