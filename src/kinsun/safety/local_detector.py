def _to_traditional(text):
    """簡體轉繁體，回 (轉換後文字, 位置對照表)。1:1 對應，位置不變。"""
    out = text.translate(_S2T)
    return out, list(range(len(text)))


def _decode_bopomofo(text):
    """注音縮寫還原成漢字，回 (還原後文字, 位置對照表)。"""
    if not _BOPO_RE.search(text):
        return text, list(range(len(text)))
    chars, index_map, i = [], [], 0
    while i < len(text):
        m = _BOPO_RE.match(text, i)
        if m:
            chars.append(_BOPOMOFO[m.group(0)])
            index_map.append(i)
            i = m.end()
            continue
        chars.append(text[i])
        index_map.append(i)
        i += 1
    return "".join(chars), index_map


# 一句話會被幾十個 pattern 比對，三種正規化不必每次重算 → 單筆快取。
#   （偵測器是單執行緒同步呼叫，一次只處理一句，單筆就夠；不用 lru_cache 免得吃記憶體。）
_VARIANT_CACHE = {}
_VARIANT_CACHE_ORDER = []


def _variants(text):
    """回 [(正規化後文字, 位置對照表), ...]，只含真的有變動的版本。"""
    hit = _VARIANT_CACHE.get(text)
    if hit is not None:
        return hit
    # 簡繁已在 detect 入口轉好，這裡不再重複
    out = [
        pair
        for pair in (_normalize(text), _strip_fillers(text), _decode_bopomofo(text))
        if pair[0] != text
    ]
    _VARIANT_CACHE[text] = out
    _VARIANT_CACHE_ORDER.append(text)
    if len(_VARIANT_CACHE_ORDER) > 32:  # 上限很小，只是為了一則訊息內的子句重用
        _VARIANT_CACHE.pop(_VARIANT_CACHE_ORDER.pop(0), None)
    return out


def _match_guarded(text, pattern, method_word=False):
    """pattern 命中且通過守門 → True。原文／去雜訊／去語氣副詞／注音還原各比對一次。

    ★所有版本都必須回原文位置過同一套守門（否定／引述／人稱）——
      這個錯誤犯過三次，每次繞過守門就誤報暴增。
    """
    for m in pattern.finditer(text):
        if _guarded(text, m.start(), method_word):
            return True
    for variant, index_map in _variants(text):  # _variants 已濾掉沒變動的版本
        for m in pattern.finditer(variant):
            original_index = index_map[m.start()] if m.start() < len(index_map) else 0
            # ★原文位置與變體位置【兩邊都要過守門】。
            #   只查原文，會漏掉「被雜訊切斷的否定詞」：
            #   「我又不是 要自殺」的命中來自正規化後的「我又不是要自殺」，
            #   守門卻回原文找「不是要」，中間卡著空格對不上 → 判 L4。
            #   只查變體，則會漏掉位置漂移後的人稱／引述框。兩邊都查最保險。
            if _guarded(text, original_index, method_word) and _guarded(
                variant, m.start(), method_word
            ):
                return True
    return False


