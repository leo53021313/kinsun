ATTR_SELF = "self"  # 長輩本人
ATTR_OTHER = "other"  # 別人的事（鄰居／親友／新聞／衛教提問）
ATTR_UNKNOWN = "unknown"  # 判斷不出來——★預設當本人處理，不可用來否決


def attribution(text):
    """回 ATTR_SELF / ATTR_OTHER / ATTR_UNKNOWN。

    ## 為什麼要跟嚴重度分開

    「嚴重度」和「這是誰的事」是兩個問題，現在被擠在同一個數字裡。
    於是「隔壁老王摔倒了」只能表達成一個 tier——而任何 tier 都不對：
    判高了會推播給家屬（那不是長輩的事），判低了又丟失了資訊。

    分開之後，嚴重度可以維持「只升不降」，歸屬另外回答「這筆該不該算在他頭上」。

    ## 安全設計

    * 只有**明確**看得出主詞是別人時才回 `ATTR_OTHER`；含糊一律 `ATTR_UNKNOWN`。
    * `ATTR_UNKNOWN` 必須當本人處理——中文常省略主詞，
      「跌倒了爬不起來」沒有主詞，那正是最該通知的句子。
    * 「別人對長輩做的事」（隔壁阿伯打我）算 `ATTR_SELF`——受害者是長輩。
    """
    # ★最高優先：本模組的守門本來就含人稱／引述／否定判斷。
    #   全部過了還判到危險以上，代表主詞就是長輩。
    #   ★實測抳到：「電視演那個自殺，我也想一了百了」
    #     模組判 L4，媒體框卻把它判成 other——那會靜音真危機。
    #     「先講電視、再講自己」是長輩典型的說法。
    if detect(text)[0] >= LEVEL_DANGER:
        return ATTR_SELF
    if _has_own_crisis(text):
        return ATTR_SELF  # 本人明講的危機
    if _ABUSE.search(text) or _VICTIM_ME.search(text):
        return ATTR_SELF  # 別人對長輩做的事，仍是長輩的事
    if _is_question(text):
        return ATTR_OTHER  # 衛教提問，沒有當事人
    if _HEARSAY.search(text) or _THIRD_VIA_ME.search(text):
        return ATTR_OTHER  # 「我朋友」「聽說」
    if _is_narrative(text):
        return ATTR_OTHER  # 明確的第三人稱主詞且無「我」
    if _HARM_MEDIA.search(text) or _WATCHING.search(text):
        return ATTR_OTHER  # 電視／新聞／連續劇
    if _FIRST_PERSON.search(text):
        return ATTR_SELF
    return ATTR_UNKNOWN


def is_risky(text, threshold=LEVEL_DANGER):
    """簡單版：有沒有問題（預設門檻＝需要通知家屬的程度）。"""
    return detect(text)[0] >= threshold


