# 容忍字元之間插入空白／標點／波浪（「我 想 死」「我想。死」「我想~死~」）。
# ★仍在原文位置比對，所以守門邏輯完全不受影響。
# ★emoji 插在關鍵詞【中間】會斷詞（「我不想😭活了」判 0）——
#   長輩邊打邊插貼圖是常態，必須跟空白、標點一樣當雜訊吃掉。
_EMOJI = (
    "\U0001f300-\U0001faff"  # 表情、符號、旗幟
    "☀-➿"  # 雜項符號與裝飾符號
    "️‍"  # 變體選擇符、零寬連接
    "⬀-⯿←-⇿"
)
_GAP = r"[\s　。、，,~～\.\-_·﹒" + _EMOJI + r"]{0,3}"


def _compile_loose(words):
    return re.compile("|".join(_GAP.join(re.escape(ch) for ch in w) for w in words))


_RE_CRISIS = _compile_loose(CRISIS_WORDS + DIALECT_CRISIS)
_RE_CRISIS_METHOD = _compile_loose(CRISIS_METHOD_WORDS)
_RE_DANGER = _compile_loose(DANGER_WORDS + DIALECT_DANGER)

# 規則式 pattern（含群組與量詞）沒辦法像詞表那樣逐字塞 _GAP，改用「正規化＋位置回映」：
# 比對在「拿掉空白標點」的版本上做，守門仍在【原文】的對應位置做 → 兩者兼得。
# （實測缺這段：「死了也沒差」判危機、「死了 也沒差」加個空格就漏。）
_NOISE = re.compile(r"[\s　。、，,~～\.\-_·﹒" + _EMOJI + r"]")


def _normalize(text):
    """回 (壓縮後文字, 位置對照表)；對照表[i] = 壓縮後第 i 字在原文的位置。"""
    chars, index_map = [], []
    for i, ch in enumerate(text):
        if not _NOISE.match(ch):
            chars.append(ch)
            index_map.append(i)
    return "".join(chars), index_map


# 語氣副詞：夾在動詞與受詞中間會讓 pattern 對不上
#   （「我不想撐了」中→「我不想【再】撐了」漏）。★絕不含否定詞，否則會把「不想死」洗成「想死」。
#   ★也不含「好／很」——那是程度副詞，擺在片語「前面」不影響相鄰性，
#     卻會把「比較好找」洗成「比較找」，害守門的排除條件對不上（實測踩到）。
#   ★語音轉文字一定會帶口語贅詞（那個、就是、齒、欸），
#     它們會夾在動詞跟受詞中間把 pattern 撠斷
_FILLER = re.compile(
    r"實在|真的|根本|其實|已經|好像|大概|反正|乾脆|老是|一直"
    r"|那個|這個|就是|然後|所以說|對啊|[齒欸嗯喔呢吧吖]"
    r"|[都再也又還太超]"
)


def _strip_fillers(text):
    """移除語氣副詞，回 (壓縮後文字, 位置對照表)。用於補『插入詞』造成的漏抓。"""
    chars, index_map, i = [], [], 0
    while i < len(text):
        m = _FILLER.match(text, i)
        if m and m.end() > i:
            i = m.end()
            continue
        chars.append(text[i])
        index_map.append(i)
        i += 1
    return "".join(chars), index_map


