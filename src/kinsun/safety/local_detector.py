_OTHER_SUBJ = re.compile(
    r"公公|婆婆|岳父|岳母|嫌犯|死者|傷者|亡者|病人|患者|家屬"
    #   ★長輩口中的鄰里稱謂——實測「樓上阿婆前幾天中風了」漏掉（2026-07-30）
    r"|阿婆|阿伯|阿姨|叔叔|伯母|嬸嬸|大嬸|大叔|老太太|老先生"
    r"|樓上|樓下|對門|隔壁|同棟|里長|鄰長"
    r"|警察|消防|檢察官|法官|里長|房東|房客|網友|版友|路人|同事|學[弟長姊妹]"
    #   ★刻意不收「他／她／他們／對方」——那些在長輩口中幾乎都是「身邊的人對我做了什麼」，
    #     不是別人的事。實測「過年他們也沒回來」被整句吃掉，那是長輩自己的孤單。
    r"|某某|該名|當事人|死傷|罹難"
    #   劇中角色也是「別人」（連續劇的男主角自殺了）
    r"|(男|女)主角|劇中|主人翁"
    # 新聞／敘事的語言標記（就算沒有人當主詞也看得出是在轉述事件）
    r"|新聞|報導|報案|通報|案件|事件|上演|戲碼|劇情|研判|初步"
    r"|排除[^。！？!?]{0,4}(他殺|輕生|外力)|外力入侵|非自願"
)


def _is_narrative(text):
    """句中在講別人的事（有第三人稱主詞，且完全沒有第一人稱）。

    ★「沒有『我』」單獨不能當條件——中文常省略主詞，長輩打「跌倒了爬不起來」
      「喘不過氣」也沒有「我」，那些是最該抓的。必須同時出現別人當主詞才算。
    """
    return bool(_OTHER_SUBJ.search(text)) and not _FIRST_PERSON.search(text)


# 勵志／比喻框：「人生嘛，跌倒了再爬起來就好」不是真的跌倒。
#   這種句子在長輩口中很常見（安慰別人、感嚇人生），
#   而它們幾乎都帶著「人生／日子＋嘛／就是」這種語氣框。
_METAPHOR = re.compile(
    r"(人生|日子|做人|做事|人活著)[^。！？!?]{0,4}"
    r"(嘛|就是|本來|都是|就像)"
    r"|(跌倒了?|摔倒了?)[^。！？!?]{0,4}"
    r"(再|就)[^。！？!?]{0,3}(爬起來|站起來)"
    r"|(不怕|不要怕|哪怕)[^。！？!?]{0,4}跌倒"
)


def _sentence_level_suppress(text, context=None):
    """整句層級的否決：第三人稱主詞、反問。

    context＝整則訊息（逐子句掃的時候傳進來）。
    ★兩條「跨子句性質」的豁免（往事康復、診斷否定）看 context，
      因為「現在好了」常常在另一個子句（「我十年前中風過，現在好了」）；
      但必須「這個子句自己也提到那件事」才套用，否則
      「我以前中風過現在好了，我想自殺」的後半句會被一起吃掉。
      其餘豁免（引述、反問、人稱）一律只看本子句。

    ★例外：長輩自己是受害者時不否決。第三人稱守門是為了擋「別人的事」
    （鄰居的婆婆去自殺了），但「別人對長輩做的事」仍然是長輩的事——
    「隔壁老王跑來打我」開頭是「隔壁」，不能因此被整句吃掉。
    """
    #   ★就算是想念句，句子裡還有別的危機詞就不豁免
    # ★總防呆：本人明講的危機，任何整段否決都不准套用（見 _has_own_crisis）
    if _has_own_crisis(text):
        return False
    if _AFFECTION.search(text) and not re.search(
        r"不想活|自殺|輕生|想不開|活不下去|撐不下去|去死|上吊|燒炭|跳樓", text
    ):
        return True
    if _is_narrative(text):  # 在講別人的事（見 _is_narrative 的說明）
        return True
    if _METAPHOR.search(text):  # 勵志／比喻（人生嘛，跌倒了再爬起來）
        return True
    # 別人受傷／生病：主詞明確是他人時不算長輩的事（我孫子在學校跌倒／里長說有人跌倒）
    if re.search(
        r"(我的?)?(孫子|孫女|兒子|女兒|媳婦|朋友|鄰居|同學|里長|阿姨|叔叔)"
        r"[^。！？!?]{0,10}(跌倒|受傷|擦傷|生病|住院|骨折|燙傷)",
        text,
    ) and not re.search(r"(打我|推我|撞我|害我)", text):
        return True
    if re.search(r"(里長|鄰居|朋友|同事)[^。！？!?]{0,4}說[^。！？!?]{0,6}有人", text):
        return True
    if _is_question(text):  # 純知識提問（中風有什麼症狀／燙傷要怎麼處理）
        return True
    # 過去式／已康復：「我十年前中風過現在好了」「我擦以前留的燙傷藥膏」
    #   ★必須有「已康復」的明確表述；且句中若有「又／現在／剛剛」等復發語，一律不豁免
    #     （原本裸的「過，」是萬用鑰匙，「我十年前中風過，現在又中風了」被整句吃掉）
    ctx = context or text
    #   ★本子句自己也要提到「那件往事」才套用；康復詞可以在別的子句
    _PAST_TOPIC = (
        r"([0-9０-９一二三四五六七八九十幾]+[年月天]前|以前|之前|當年|上次"
        r"|上個?月|上禮拜|上星期|前陣子|那時候|年輕[時的]|小時候|曾經"
        r"|中風|跌倒|燙|開刀|住院|想不開|藥膏|疤)"
    )
    if (
        re.search(_PAST_TOPIC, text)
        and re.search(
            r"([0-9０-９一二三四五六七八九十幾]+[年月天]前|以前|之前|當年|上次"
            r"|上個?月|上禮拜|上星期|前陣子|那時候|年輕[時的]|小時候|曾經)",
            ctx,
        )
        and re.search(
            r"(已經)?(好了|好多了|好很多|改善了|控制住了"
            r"|康復了?|痊癒|沒事了|沒再犯|沒再發作|留下的疤|藥膏"
            # ★心理上的「已經走過去了」也算康復
            #   （我年輕的時候曾經想不開，現在早就想通了）
            r"|想通了?|看開了?|走出來了?|放下了?)",
            ctx,
        )
        and not re.search(
            r"(又|再度|再次|現在|剛剛|今天|昨天|這次|最近|還是|依然|仍然|一直)"
            r"[^。！？!?]{0,6}"
            r"(中風|跌倒|摔|想不開|想死|不想活|燙|發作|痛|昏|暈|出血|爬不起來|喘)",
            ctx,
        )
    ):
        return True
    # 診斷否定：只擋「診斷結果是陰性」這一件事，★不可整句歸零——
    #   長輩的典型口氣是「沒事啦」＋真話（「我不想活了，沒事啦」），
    #   裸詞豁免會把最該抓的族群整句吃掉（第二輪驗收揪到的最嚴重 bug）。
    #   ★同樣是跨子句的：診斷結果常在另一句。但本子句必須自己提到癌／腫瘤／檢查，
    #     否則「檢查報告不是癌症，我跌倒了爬不起來」的後半句會被吃掉。
    if (
        re.search(r"癌|腫瘤|良性|惡性|報告|檢查", text)
        and re.search(
            r"(沒有|不是|並非)[^。！？!?]{0,4}(癌症?|惡性|腫瘤)"
            r"|(是|為)良性",
            ctx,
        )
        and not re.search(r"(想死|不想活|自殺|想不開|跳|上吊|燒炭|撐不下去|活不下去)", text)
    ):
        return True
    if _ABUSE.search(text) or _VICTIM_ME.search(text):  # 長輩是被做的那一方→他的事
        return False
    # 身邊有武器／縱火威脅：就算主詞是別人，那也是長輩所處環境的危險
    #   （「隔壁老王要開槍教訓人」＝環境危險，不同於「鄰居想不開」＝別人的事）
    if re.search(r"開槍|拿槍|持刀|拿刀|放火|縱火|砍人|殺人", text):
        return False
    if _THIRD_VIA_ME.search(text) or _HEARSAY.search(text):
        return True
    # 第三人稱主詞只在「整句沒有我」時才否決（有我＝長輩可能是當事人）
    if _THIRD_PERSON.search(text) and "我" not in text:
        return True
    return any(w in text for w in _RHETORICAL)


# 「想死你了」「想死我了」＝想念，不是危機。★整句判斷，不可用位置偏移去猜
# （寫過一版用 index 偏移，結果把「跟【你】說再見」也一起擋掉）。
#   ★必須帶「了」才算想念（「想死你了」）。
#     原本裸的「想死＋代名詞」會打中「我想死【我想死】」——
#     長輩連打同一句正是激動的訊號，反而被靈音（第三輪驗收 9/9 全滅）。
_AFFECTION = re.compile(r"想死(你|妳|您|他|她)了|想死我了|(好|真|超)想你")


# ══ 通用防呆：任何「整段否決」的守門，都必須先過這一關 ══
#   這場踩了四次同一個坑（沒事豁免／往事豁免／語氣副詞正規化／觀看框），
#   每次都是「為了擋一種誤報，順手把整段話歸零」，而長輩最典型的講法就是
#   「先講別的、再講真話」。凡是本人第一人稱明講的危機，一律不准被任何框吃掉。
#   ★「想死你了」是想念，不算——這裡如果收太寬，會把想念句一起放行
#   ★「我朋友想不開」的主詞是朋友不是我——「我」後面接別人就不算本人
_OWN_CRISIS = re.compile(
    r"我(?!朋友|鄰居|同事|同學|認識|兒子|女兒|孫子|孫女|媳婦|女婿"
    r"|老伴|先生|太太|老公|老婆|[媽爸哥姊姐弟妹])"
    r"[^。！？!?]{0,4}(想死(?![你妳您他她我]了)|想自殺|要自殺|不想活|想不開"
    r"|活不下去|撐不下去|去死|想跳樓|想上吊|想燒炭|割腕|想結束生命)"
)


# ★長輩自己是「施事者」的傷害行為，也不准被第三人稱守門吃掉。
#   判準是「長輩是不是當事人」——當受害者算、當加害者也算（那是精神狀態警訊）。
#   實測：「我昨天打了【我】鄰居」因為「我鄰居」被當第三人稱而整句歸零。
_OWN_AGGRESSION = re.compile(
    #   ★中文常省略主詞：「剛剛出門暴打了一個路人」沒有「我」，
    #     但「時間副詞＋暴力動詞」已足以確認是本人做的——
    #     不收的話會被敘事框（路人＝第三人稱）整句吃掉。
    r"(剛剛|今天|剛才|方才|一氣之下)[^。！？!?]{0,6}"
    r"(暴打|揍了|踹了|打傷|打了)[^。！？!?]{0,4}"
    r"(路人|別人|人家|小孩|鄰居|店員|看護)"
    r"|我[^。！？!?]{0,4}"
    #   ★否定預查放在【時態助詞之後】——放前面的話，
    #     「打【了】電話給我兒子」會從「了」繞過去，直接撃中後面的「兒子」
    r"(打|揍|踹|甩|掐|咬|推倒)[了過]"
    r"(?!電話|給|麻將|球|牌|字|掃|拳|太極|棉被|蚊子|針|line|LINE)"
    r"[^。！？!?]{0,2}(我的?)?"
    r"(兒子|女兒|媳婦|女婿|孫子|孫女|看護|外勞|鄰居|太太|先生|老伴|老婆|老公"
    r"|婆婆|公公|護士|店員|小孩)"
)


def _has_own_crisis(text):
    """這段文字裡有沒有「長輩本人是當事人」的危機——本人求死，或本人動手傷人。

    有的話，任何整段否決（引述框／人稱框／往事框…）都不准套用。
    """
    return bool(_OWN_CRISIS.search(text) or _OWN_AGGRESSION.search(text))


def _guarded(text, index, method_word=False):
    """位置 index 的這次命中，是否通過四層守門。True＝真的算命中。
    method_word=True 時額外套用「不想／不要」否定（只對方法類）。"""
    # ★取上下文之前先去雜訊——否定詞被空格／標點／emoji 切開就對不上。
    #   「我又不是 要自殺」的 pre8 是「我又不是 要」，找不到「不是要」→ 判 L4。
    #   關鍵詞比對有正規化，守門的上下文卻沒有，這個不對稱是誤報的來源。
    _clean_pre = _NOISE.sub("", text[max(0, index - 16) : index])
    immed = _clean_pre[-1:] if _clean_pre else ""
    pre3 = _clean_pre[-3:]
    pre8 = _clean_pre[-8:]
    # ★雙重否定＝肯定：「我不是不想死」＝我想死。必須排在所有否定檢查【之前】，
    #   否則緊貼的那個「不」會先把它擋掉。
    if re.search(r"不是不|沒有不|並非不|不會不", pre8):
        return True
    if method_word and any(w in pre8 for w in _NEG_METHOD_ONLY):
        return False
    clause_start = max((text.rfind(c, 0, index) for c in _CLAUSE_SEP), default=-1) + 1
    clause = text[clause_start:index]
    # ★整個子句（不只命中之前那半段）——「想死的是我」這種倒裝，「我」在後面
    ends = [text.find(c, index) for c in _CLAUSE_SEP]
    clause_end = min([e for e in ends if e >= 0], default=len(text))
    full_clause = text[clause_start:clause_end]
    # 保命優先：子句裡只要出現「我」就不套媒體框／罵人框／人稱框
    #   （「電視演完我也想死」是本人在講自己，必須照樣命中）
    has_me = "我" in full_clause
    # ★第三人稱守門原本只存在於「整則」層級，於是
    #   「鄰居的婆婆去自殺了，我很難過」——後半句的「我」讓整則不算第三人稱——
    #   前半句就直接命中 L4。人稱是**子句**的屬性，必須在這裡判。
    #   ★本人是當事人（求死或本人動手傷人）時不套人稱框——
    #     「剛剛出門暴打了一個路人」沒有「我」，但那是長輩做的事。
    if (
        not has_me
        and not _has_own_crisis(full_clause)
        and (_THIRD_PERSON.match(full_clause) or _is_narrative(full_clause))
    ):
        return False
    if immed in _NEG_IMMED:
        return False
    # 「是不是中風」「會不會是…」是【疑問求助】，不是否認——不可當否定
    if not any(q in pre8 for q in ("是不是", "會不會", "是否", "有沒有可能")):
        if any(w in pre3 for w in _NEG_NEAR):
            return False
    if any(w in pre8 for w in _NEG_INTENT):
        return False
    # ★觀看框不受 has_me 保護——這裡的「我」是觀看者，不是當事人。
    #   但仍要過 _has_own_crisis：「我在看電視 我想自殺」不可以被整段吃掉。
    if _WATCHING.search(full_clause) and not _has_own_crisis(full_clause):
        return False
    if _QUOTE_FRAME.search(clause) and not has_me:
        return False
    if _SECOND_PERSON.search(clause) and not has_me:
        return False
    return True


