def _is_question(text):
    """純知識提問 → 不算本人有狀況。

    ★判準是「整句有沒有『我』」，不是靠 _SELF_COMPLAINT 那種窄 pattern——
      「我的手舉不高了 是不是中風」「我看著陽台想說跳下去會怎樣」都有我，
      那是求助不是查資料，不可被問句框吃掉。
    """
    # ★「在想要怎麼…」是反芻，不是提問。
    #   實測「這幾天一直在想要怎麼了結自己」因為有「要怎麼」
    #   且整句無「我」，被當成查資料而整句歸零。
    #   ★分界是「反芻標記」不是「有沒有危機詞」——
    #     衛教提問（老人家為什麼會想不開）本來就帶危機詞。
    if re.search(
        r"(一直|最近|這幾天|常常|每天|時常)[^。！？!?]{0,4}在?想"
        r"|我在想|我想著",
        text,
    ):
        return False
    return bool(_QUESTION_FRAME.search(text)) and "我" not in text


# 轉述標記：句子雖有「我」，但講的是聽來的別人的事
